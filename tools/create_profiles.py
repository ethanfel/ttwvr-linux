"""Initialize a new portable TTW MO2 instance; refuses to replace existing config."""
import argparse
import configparser
import json
from pathlib import Path
import shutil


def windows_path(path):
    return ("Z:" + str(path.resolve()).replace("/", "\\")).replace("\\", "\\\\")


def names_from_json(path):
    names = json.loads(path.read_text())
    if not isinstance(names, list) or not names or not all(
        isinstance(n, str) and n and not any(c in n for c in "\\/\r\n") and
        n not in (".", "..") for n in names
    ):
        raise ValueError("expected a nonempty JSON array of plain filenames/mod names")
    if len(set(n.casefold() for n in names)) != len(names):
        raise ValueError("duplicate names in list")
    return names


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("mo2", "fnv", "ini-dir", "custom-ini", "mods", "plugins"):
        parser.add_argument("--" + name, required=True, type=Path)
    parser.add_argument("--vr-mod", required=True)
    args = parser.parse_args()
    mo2 = args.mo2.resolve()
    try:
        mods = names_from_json(args.mods)
        plugins = names_from_json(args.plugins)
    except (ValueError, OSError) as exc:
        parser.error(str(exc))
    if args.vr_mod not in mods:
        parser.error("VR mod must be in the ordered mod list")
    for mod in mods:
        if not (mo2 / "mods" / mod).is_dir():
            parser.error(f"missing staged mod: {mod}")
    for file in [mo2 / "ModOrganizer.exe", args.fnv / "FalloutNV.exe",
                 args.ini_dir / "Fallout.ini", args.ini_dir / "FalloutPrefs.ini",
                 args.custom_ini]:
        if not file.is_file():
            parser.error(f"missing prerequisite file: {file}")
    targets = [mo2 / "ModOrganizer.ini"] + [mo2 / "profiles" / n for n in ("TTW - Flat", "TTW - VR")]
    if any(p.exists() for p in targets):
        parser.error("instance/profile already configured; refusing to replace it")

    config = configparser.RawConfigParser()
    config.optionxform = str
    # MO2 resolves the internal gameName(), not displayGameName().
    config["General"] = {"gameName": "TTW",
                         "gamePath": windows_path(args.fnv), "game_edition": "Steam",
                         "selected_profile": "@ByteArray(TTW - Flat)"}
    config["Settings"] = {"base_directory": windows_path(mo2),
                          "profile_local_inis": "true", "profile_local_saves": "true",
                          "profile_archive_invalidation": "true"}
    config["customExecutables"] = {
        "size": "1", "1\\title": "Tale of Two Wastelands",
        "1\\binary": windows_path(args.fnv / "FalloutNV.exe"),
        "1\\workingDirectory": windows_path(args.fnv), "1\\arguments": "",
        "1\\steamAppID": "22380", "1\\toolbar": "false", "1\\hide": "false",
        "1\\ownicon": "true",
    }
    (mo2 / "portable.txt").touch(exist_ok=True)
    for vr in (False, True):
        profile = mo2 / "profiles" / ("TTW - VR" if vr else "TTW - Flat")
        profile.mkdir(parents=True)
        (profile / "saves").mkdir()
        (profile / "settings.ini").write_text("[General]\nLocalSaves=true\nLocalSettings=true\n")
        # Omit AutomaticArchiveInvalidation: MO2 initializes the actual BSA and
        # INI entries on first load using profile_archive_invalidation above.
        lines = [("+" if vr or mod != args.vr_mod else "-") + mod for mod in reversed(mods)]
        (profile / "modlist.txt").write_text("# Generated by ttwvr-linux\n" + "\n".join(lines) + "\n")
        for name in ("plugins.txt", "loadorder.txt"):
            (profile / name).write_text("# Generated by ttwvr-linux\n" + "\n".join(plugins) + "\n")
        (profile / "archives.txt").touch()
        for name in ("Fallout.ini", "FalloutPrefs.ini"):
            shutil.copy2(args.ini_dir / name, profile / name)
        shutil.copy2(args.custom_ini, profile / "FalloutCustom.ini")
    with (mo2 / "ModOrganizer.ini").open("w") as stream:
        config.write(stream, space_around_delimiters=False)
    print(f"Created TTW - Flat and TTW - VR: {len(mods)} staged mods, {len(plugins)} plugins.")
    print("MO2 runtime initialization, archive invalidation and game launch still require verification.")


if __name__ == "__main__":
    main()
